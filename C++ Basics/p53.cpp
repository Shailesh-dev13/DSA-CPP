//bitwise and operation
#include <iostream>
using namespace std;
int main(){
    int a=3,b=7;
    cout<<(a^b)<<endl;//xor operator
    cout<<(4<<1)<<endl;//left shift operator
    cout<<(10<<2)<<endl;//left shift operator
    cout<<(10>>1)<<endl;//right shift operator
    cout<<(8>>2)<<endl;//right shift operator
    cout<<(6&10)<<endl;//bitwise and operator
    cout<<(6|10)<<endl;//bitwise or operator
    cout<<(6^10)<<endl;//bitwise xor operator

    return 0;

}